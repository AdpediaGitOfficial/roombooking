import { z } from "zod";
import { LOST_FOUND_MANAGE_ROLES, LOST_FOUND_OPERATE_ROLES, LOST_FOUND_VIEW_ROLES } from "@sam/core/modules/lost-found/access";
import type * as svc from "@sam/core/modules/lost-found/service";
import { cuid, fileInput, fileList, op, out, type Ret } from "../define";

const text = (max: number) => z.string().max(max).optional();

export const lostFound = {
  register: op({
    id: "lostFound.register",
    method: "GET",
    path: "/v1/lost-found",
    summary: "The found-items register for a filter, with summary counts",
    tag: "Lost and found",
    access: LOST_FOUND_VIEW_ROLES,
    input: z.object({ filter: z.enum(["open", "reported", "stored", "claims", "due", "returned", "disposed", "all"]).default("open"), q: text(200) }),
    output: out<Ret<typeof svc.getRegisterView>>(),
  }),
  options: op({
    id: "lostFound.options",
    method: "GET",
    path: "/v1/lost-found/options",
    summary: "Sites and residents for the registration and claim forms",
    tag: "Lost and found",
    access: LOST_FOUND_OPERATE_ROLES,
    input: z.object({}),
    output: out<Ret<typeof svc.registerOptions>>(),
  }),
  mine: op({
    id: "lostFound.mine",
    method: "GET",
    path: "/v1/lost-found/mine",
    summary: "Open found items a resident can browse, and the resident's own claims",
    tag: "Lost and found",
    input: z.object({ q: text(200) }),
    output: out<Ret<typeof svc.getMyPortal>>(),
  }),
  getMine: op({
    id: "lostFound.getMine",
    method: "GET",
    path: "/v1/lost-found/mine/:id",
    summary: "One found item as a resident sees it: public details and their own claim",
    tag: "Lost and found",
    input: z.object({ id: cuid() }),
    output: out<Ret<typeof svc.getMyItemView>>(),
  }),
  get: op({
    id: "lostFound.get",
    method: "GET",
    path: "/v1/lost-found/items/:id",
    summary: "One item with claims, timeline, photos and look-alike open items",
    tag: "Lost and found",
    access: LOST_FOUND_VIEW_ROLES,
    input: z.object({ id: cuid() }),
    output: out<Ret<typeof svc.getItemView>>(),
  }),
  create: op({
    id: "lostFound.create",
    method: "POST",
    path: "/v1/lost-found/items",
    summary: "Register a found item, optionally with photos",
    tag: "Lost and found",
    access: LOST_FOUND_OPERATE_ROLES,
    multipart: true,
    input: z.object({
      siteId: cuid(), description: z.string().max(2000), category: text(100), foundLocation: text(300), foundAt: z.string().max(40), foundByName: text(200),
      storageLocation: text(200), notes: text(2000), retentionDays: z.coerce.number().int().optional(), photos: fileList(5),
    }),
    output: out<Ret<typeof svc.registerItem>>(),
  }),
  update: op({
    id: "lostFound.update",
    method: "PUT",
    path: "/v1/lost-found/items/:id",
    summary: "Edit an item's description and details",
    tag: "Lost and found",
    access: LOST_FOUND_OPERATE_ROLES,
    input: z.object({ id: cuid(), description: z.string().max(2000), category: text(100), foundLocation: text(300), foundByName: text(200), notes: text(2000), retainUntil: text(40) }),
    output: out<Ret<typeof svc.updateItem>>(),
  }),
  store: op({
    id: "lostFound.store",
    method: "POST",
    path: "/v1/lost-found/items/:id/store",
    summary: "Record where an item is being kept",
    tag: "Lost and found",
    access: LOST_FOUND_OPERATE_ROLES,
    input: z.object({ id: cuid(), storageLocation: z.string().max(200), notes: text(2000) }),
    output: out<Ret<typeof svc.storeItem>>(),
  }),
  addPhoto: op({
    id: "lostFound.addPhoto",
    method: "POST",
    path: "/v1/lost-found/items/:id/photos",
    summary: "Add a photo to an item",
    tag: "Lost and found",
    access: LOST_FOUND_OPERATE_ROLES,
    multipart: true,
    input: z.object({ id: cuid(), photo: fileInput }),
    output: out<Ret<typeof svc.addPhoto>>(),
  }),
  recordClaim: op({
    id: "lostFound.recordClaim",
    method: "POST",
    path: "/v1/lost-found/items/:id/claims",
    summary: "Record a claim for a resident or a walk-in claimant",
    tag: "Lost and found",
    access: LOST_FOUND_OPERATE_ROLES,
    input: z.object({ id: cuid(), evidence: z.string().max(2000), claimantStaffId: cuid().optional(), claimantName: text(200), claimantContact: text(200) }),
    output: out<Ret<typeof svc.recordClaim>>(),
  }),
  claim: op({
    id: "lostFound.claim",
    method: "POST",
    path: "/v1/lost-found/mine/:id/claim",
    summary: "A resident claims an item as their own",
    tag: "Lost and found",
    input: z.object({ id: cuid(), evidence: z.string().max(2000), claimantContact: text(200) }),
    output: out<Ret<typeof svc.submitMyClaim>>(),
  }),
  decideClaim: op({
    id: "lostFound.decideClaim",
    method: "POST",
    path: "/v1/lost-found/claims/:id/decision",
    summary: "Verify or reject a claim",
    tag: "Lost and found",
    access: LOST_FOUND_OPERATE_ROLES,
    input: z.object({ id: cuid(), verified: z.union([z.boolean(), z.stringbool()]), note: text(2000) }),
    output: out<Ret<typeof svc.decideClaim>>(),
  }),
  withdrawClaim: op({
    id: "lostFound.withdrawClaim",
    method: "POST",
    path: "/v1/lost-found/claims/:id/withdraw",
    summary: "Withdraw a pending claim (the claimant, or an operator)",
    tag: "Lost and found",
    input: z.object({ id: cuid() }),
    output: out<Ret<typeof svc.withdrawClaim>>(),
  }),
  handOver: op({
    id: "lostFound.handOver",
    method: "POST",
    path: "/v1/lost-found/items/:id/handover",
    summary: "Record the handover of a verified item, optionally with photo evidence",
    tag: "Lost and found",
    access: LOST_FOUND_OPERATE_ROLES,
    multipart: true,
    input: z.object({ id: cuid(), recipientName: text(200), note: text(2000), evidence: fileInput.optional() }),
    output: out<Ret<typeof svc.handOver>>(),
  }),
  dispose: op({
    id: "lostFound.dispose",
    method: "POST",
    path: "/v1/lost-found/items/:id/dispose",
    summary: "Authorise and record the disposal of an unclaimed item",
    tag: "Lost and found",
    access: LOST_FOUND_MANAGE_ROLES,
    input: z.object({ id: cuid(), method: z.string().max(100), note: z.string().max(2000) }),
    output: out<Ret<typeof svc.disposeItem>>(),
  }),
};

import { z } from "zod";
import { ALLOCATION_ADMIN_ROLES, ALLOCATION_OPERATE_ROLES, ALLOCATION_VIEW_ROLES } from "@sam/core/modules/allocations/access";
import type * as svc from "@sam/core/modules/allocations/service";
import { cuid, isoDate, op, out, type Ret } from "../define";

const note = z.string().max(2000).optional();

export const allocations = {
  list: op({
    id: "allocations.list",
    method: "GET",
    path: "/v1/allocations",
    summary: "Allocations by state, optionally for one person (latest 200)",
    tag: "Allocations",
    access: ALLOCATION_VIEW_ROLES,
    input: z.object({ filter: z.enum(["active", "upcoming", "history", "all"]).default("active"), staffId: cuid().optional() }),
    output: out<Ret<typeof svc.listAllocations>>(),
  }),
  formOptions: op({
    id: "allocations.formOptions",
    method: "GET",
    path: "/v1/allocations/form-options",
    summary: "Active staff and buildings for the allocation and transfer forms",
    tag: "Allocations",
    access: ALLOCATION_OPERATE_ROLES,
    input: z.object({}),
    output: out<Ret<typeof svc.allocationFormOptions>>(),
  }),
  availableBeds: op({
    id: "allocations.availableBeds",
    method: "GET",
    path: "/v1/allocations/available-beds",
    summary: "Beds free for the whole of a stay",
    tag: "Allocations",
    access: ALLOCATION_OPERATE_ROLES,
    input: z.object({
      startDate: isoDate(),
      endDate: isoDate().optional(),
      siteId: cuid().optional(),
      buildingId: cuid().optional(),
      gender: z.enum(["ANY", "MALE", "FEMALE"]).optional(),
      excludeBedId: cuid().optional(),
    }),
    output: out<Ret<typeof svc.findAvailableBeds>>(),
  }),
  get: op({
    id: "allocations.get",
    method: "GET",
    path: "/v1/allocations/:id",
    summary: "One allocation with resident, bed, transfer chain and check-out blockers",
    tag: "Allocations",
    access: ALLOCATION_VIEW_ROLES,
    input: z.object({ id: cuid() }),
    output: out<NonNullable<Ret<typeof svc.getAllocationDetail>>>(),
  }),
  allocate: op({
    id: "allocations.allocate",
    method: "POST",
    path: "/v1/allocations",
    summary: "Allocate a bed to a staff member",
    tag: "Allocations",
    access: ALLOCATION_OPERATE_ROLES,
    input: z.object({ staffId: cuid(), bedId: cuid(), startDate: isoDate(), endDate: isoDate().optional(), reason: z.string().max(500).optional() }),
    output: out<Ret<typeof svc.allocate>>(),
  }),
  checkIn: op({
    id: "allocations.checkIn",
    method: "POST",
    path: "/v1/allocations/:id/check-in",
    summary: "Check a resident in",
    tag: "Allocations",
    access: ALLOCATION_OPERATE_ROLES,
    input: z.object({ id: cuid(), notes: note }),
    output: out<Ret<typeof svc.checkIn>>(),
  }),
  checkOut: op({
    id: "allocations.checkOut",
    method: "POST",
    path: "/v1/allocations/:id/check-out",
    summary: "Check a resident out; administrators may override clearance blockers with a reason",
    tag: "Allocations",
    access: ALLOCATION_OPERATE_ROLES,
    input: z.object({ id: cuid(), notes: note, overrideReason: z.string().max(500).optional() }),
    output: out<Ret<typeof svc.checkOut>>(),
  }),
  cancel: op({
    id: "allocations.cancel",
    method: "POST",
    path: "/v1/allocations/:id/cancel",
    summary: "Cancel a confirmed allocation",
    tag: "Allocations",
    access: ALLOCATION_ADMIN_ROLES,
    input: z.object({ id: cuid(), reason: z.string().min(1).max(500) }),
    output: out<Ret<typeof svc.cancel>>(),
  }),
  transfer: op({
    id: "allocations.transfer",
    method: "POST",
    path: "/v1/allocations/:id/transfer",
    summary: "Move a resident to another bed now or on a future date",
    tag: "Allocations",
    access: ALLOCATION_OPERATE_ROLES,
    input: z.object({ id: cuid(), toBedId: cuid(), effectiveDate: isoDate(), reason: z.string().min(1).max(500), requestId: cuid().optional() }),
    output: out<Ret<typeof svc.transfer>>(),
  }),
};

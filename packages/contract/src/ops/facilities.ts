import { z } from "zod";
import { FACILITY_MANAGE_ROLES, FACILITY_OPERATE_ROLES, FACILITY_VIEW_ROLES } from "@sam/core/modules/facilities/access";
import type * as svc from "@sam/core/modules/facilities/service";
import { bool, cuid, isoDate, op, out, type Ret } from "../define";

const text = (max: number) => z.string().max(max).optional();
const slot = { date: isoDate(), startTime: z.string().regex(/^\d{2}:\d{2}$/, "Use the format HH:MM"), durationMinutes: z.number().int(), headcount: z.number().int().default(1) };

export const facilities = {
  overview: op({
    id: "facilities.overview",
    method: "GET",
    path: "/v1/facilities",
    summary: "Every facility with 30-day utilisation, bookings awaiting approval and next-24-hour load",
    tag: "Facilities",
    access: FACILITY_VIEW_ROLES,
    input: z.object({}),
    output: out<Ret<typeof svc.getOverview>>(),
  }),
  mine: op({
    id: "facilities.mine",
    method: "GET",
    path: "/v1/facilities/mine",
    summary: "Facilities open for booking and the signed-in user's own bookings",
    tag: "Facilities",
    input: z.object({}),
    output: out<Ret<typeof svc.getMyOverview>>(),
  }),
  getMine: op({
    id: "facilities.getMine",
    method: "GET",
    path: "/v1/facilities/mine/:id",
    summary: "A facility's availability for a day, with one of the user's bookings loaded for amendment",
    tag: "Facilities",
    input: z.object({ id: cuid(), date: text(10), amend: cuid().optional() }),
    output: out<Ret<typeof svc.getMyFacilityView>>(),
  }),
  get: op({
    id: "facilities.get",
    method: "GET",
    path: "/v1/facilities/:id",
    summary: "A facility's schedule for a day, as operations staff see it",
    tag: "Facilities",
    access: FACILITY_VIEW_ROLES,
    input: z.object({ id: cuid(), date: text(10) }),
    output: out<Ret<typeof svc.getFacilityView>>(),
  }),
  create: op({
    id: "facilities.create",
    method: "POST",
    path: "/v1/facilities",
    summary: "Add a facility",
    tag: "Facilities",
    access: FACILITY_MANAGE_ROLES,
    input: z.object({ siteId: cuid(), code: z.string().max(40), name: z.string().max(200), capacity: z.number().int() }),
    output: out<Ret<typeof svc.createFacility>>(),
  }),
  update: op({
    id: "facilities.update",
    method: "PUT",
    path: "/v1/facilities/:id",
    summary: "Save facility settings: details, opening hours and booking rules (raw form fields, validated here)",
    tag: "Facilities",
    access: FACILITY_MANAGE_ROLES,
    input: z.object({ id: cuid(), fields: z.record(z.string(), z.string()) }),
    output: out<Ret<typeof svc.saveFacilitySettings>>(),
  }),
  book: op({
    id: "facilities.book",
    method: "POST",
    path: "/v1/facilities/:id/bookings",
    summary: "Book a slot (staff may book on behalf of another user)",
    tag: "Facilities",
    input: z.object({ id: cuid(), userId: cuid().optional(), ...slot, purpose: text(500), idempotencyKey: text(100) }),
    output: out<Ret<typeof svc.createBooking>>(),
  }),
  amend: op({
    id: "facilities.amend",
    method: "PUT",
    path: "/v1/facilities/bookings/:id",
    summary: "Move or resize a booking",
    tag: "Facilities",
    input: z.object({ id: cuid(), ...slot }),
    output: out<Ret<typeof svc.amendBooking>>(),
  }),
  cancel: op({
    id: "facilities.cancel",
    method: "POST",
    path: "/v1/facilities/bookings/:id/cancel",
    summary: "Cancel a booking (owners, or managers with a reason)",
    tag: "Facilities",
    input: z.object({ id: cuid(), reason: text(500) }),
    output: out<Ret<typeof svc.cancelBooking>>(),
  }),
  decide: op({
    id: "facilities.decide",
    method: "POST",
    path: "/v1/facilities/bookings/:id/decision",
    summary: "Approve or decline a booking that needs approval",
    tag: "Facilities",
    access: FACILITY_MANAGE_ROLES,
    input: z.object({ id: cuid(), approve: bool(), note: text(500) }),
    output: out<Ret<typeof svc.decideBooking>>(),
  }),
  attendance: op({
    id: "facilities.attendance",
    method: "POST",
    path: "/v1/facilities/bookings/:id/attendance",
    summary: "Mark a booking used or a no-show",
    tag: "Facilities",
    access: FACILITY_OPERATE_ROLES,
    input: z.object({ id: cuid(), attended: bool() }),
    output: out<Ret<typeof svc.recordAttendance>>(),
  }),
};

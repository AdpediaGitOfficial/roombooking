import { z } from "zod";
import { KEY_MANAGE_ROLES, KEY_OPERATE_ROLES, KEY_VIEW_ROLES } from "@sam/core/modules/keys/access";
import type * as svc from "@sam/core/modules/keys/service";
import { bool, cuid, op, out, pageInput, type Ret } from "../define";

const text = (max: number) => z.string().max(max).optional();

export const keys = {
  register: op({
    id: "keys.register",
    method: "GET",
    path: "/v1/keys",
    summary: "The key register for a filter, with summary counts",
    tag: "Keys",
    access: KEY_VIEW_ROLES,
    input: z.object({ filter: z.enum(["all", "available", "issued", "overdue", "exceptions", "retired"]).default("all"), ...pageInput }),
    output: out<Ret<typeof svc.getRegister>>(),
  }),
  registerOptions: op({
    id: "keys.registerOptions",
    method: "GET",
    path: "/v1/keys/register-options",
    summary: "Sites, rooms and facilities a key can be registered against",
    tag: "Keys",
    access: KEY_MANAGE_ROLES,
    input: z.object({}),
    output: out<Ret<typeof svc.registerOptions>>(),
  }),
  forRoom: op({
    id: "keys.forRoom",
    method: "GET",
    path: "/v1/keys/rooms/:roomId",
    summary: "Keys that open a room, with who holds them",
    tag: "Keys",
    access: KEY_VIEW_ROLES,
    input: z.object({ roomId: cuid() }),
    output: out<Ret<typeof svc.keysForRoom>>(),
  }),
  get: op({
    id: "keys.get",
    method: "GET",
    path: "/v1/keys/:id",
    summary: "One key with its full issue and return history",
    tag: "Keys",
    access: KEY_VIEW_ROLES,
    input: z.object({ id: cuid() }),
    output: out<NonNullable<Ret<typeof svc.getKey>>>(),
  }),
  create: op({
    id: "keys.create",
    method: "POST",
    path: "/v1/keys",
    summary: "Register a new key",
    tag: "Keys",
    access: KEY_MANAGE_ROLES,
    input: z.object({ siteId: cuid(), code: z.string().max(60), label: text(200), roomId: cuid().optional(), facilityId: cuid().optional(), allowCopies: bool().default(false), notes: text(2000) }),
    output: out<Ret<typeof svc.registerKey>>(),
  }),
  issue: op({
    id: "keys.issue",
    method: "POST",
    path: "/v1/keys/:id/issue",
    summary: "Issue a key to a resident or a named holder",
    tag: "Keys",
    access: KEY_OPERATE_ROLES,
    input: z.object({ id: cuid(), holderStaffId: cuid().optional(), holderName: text(200), condition: text(40), expectedReturnAt: text(40), notes: text(2000) }),
    output: out<Ret<typeof svc.issueKey>>(),
  }),
  returnKey: op({
    id: "keys.return",
    method: "POST",
    path: "/v1/keys/:id/return",
    summary: "Record a key coming back",
    tag: "Keys",
    access: KEY_OPERATE_ROLES,
    input: z.object({ id: cuid(), condition: text(40), notes: text(2000) }),
    output: out<Ret<typeof svc.returnKey>>(),
  }),
  exception: op({
    id: "keys.exception",
    method: "POST",
    path: "/v1/keys/:id/exception",
    summary: "Report a key lost, found or damaged, send it for repair or back, or retire it",
    tag: "Keys",
    access: KEY_MANAGE_ROLES,
    input: z.object({ id: cuid(), kind: z.enum(["LOST", "FOUND", "DAMAGED", "SEND_REPAIR", "BACK_REPAIR", "RETIRE"]), notes: z.string().max(2000), incidentRef: text(100) }),
    output: out<{ message: string }>(),
  }),
  replace: op({
    id: "keys.replace",
    method: "POST",
    path: "/v1/keys/:id/replace",
    summary: "Replace a lost or damaged key with a new one",
    tag: "Keys",
    access: KEY_MANAGE_ROLES,
    input: z.object({ id: cuid(), newCode: z.string().max(60), notes: text(2000) }),
    output: out<Ret<typeof svc.replaceKey>>(),
  }),
};
